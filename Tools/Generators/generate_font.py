#!/usr/bin/env python3
"""Bakes the UI font (DejaVu Sans, Bitstream Vera license) into a C++ header:
an alpha atlas (4-bit, hex encoded) + per-glyph metrics for ASCII 32..126.
Usage: generate_font.py <font.ttf> <pixel size> <out.h>"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
glyphs = []
for c in range(32, 127):
    ch = chr(c)
    l, t, r, b = font.getbbox(ch)
    adv = font.getlength(ch)
    glyphs.append((c, l, t, r, b, adv))

W = 256
pad = 1
x = y = pad
rowh = 0
places = []
for (c, l, t, r, b, adv) in glyphs:
    w, h = max(r - l, 0), max(b - t, 0)
    if x + w + pad > W:
        x = pad; y += rowh + pad; rowh = 0
    places.append((x, y, w, h))
    x += w + pad; rowh = max(rowh, h)
H = y + rowh + pad + 2
img = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(img)
for (c, l, t, r, b, adv), (px, py, w, h) in zip(glyphs, places):
    d.text((px - l, py - t), chr(c), font=font, fill=255)
# solid white texel for untextured quads at bottom-right corner (2x2)
img.putpixel((W - 1, H - 1), 255); img.putpixel((W - 2, H - 1), 255)
img.putpixel((W - 1, H - 2), 255); img.putpixel((W - 2, H - 2), 255)

px = list(img.getdata())
nib = [min(15, (v + 8) // 17) for v in px]
packed = "".join("%x" % n for n in nib)
lines = [packed[i:i + 120] for i in range(0, len(packed), 120)]

with open(out, "w") as f:
    f.write("#pragma once\n// GENERATED by Tools/Generators/generate_font.py - do not edit.\n")
    f.write("// Font: DejaVu Sans %dpx (Bitstream Vera / DejaVu license, see ThirdParty/fonts).\n\n" % size)
    f.write("namespace Lapis::FontData {\n\n")
    f.write("constexpr int AtlasWidth = %d;\nconstexpr int AtlasHeight = %d;\n" % (W, H))
    f.write("constexpr int Ascent = %d;\nconstexpr int LineHeight = %d;\n" % (ascent, ascent + descent))
    f.write("constexpr int WhiteX = %d, WhiteY = %d; // solid texel\n\n" % (W - 2, H - 2))
    f.write("struct Glyph { short X, Y, W, H, OffX, OffY; float Advance; };\n\n")
    f.write("// ASCII 32..126\nconstexpr Glyph Glyphs[95] = {\n")
    for (c, l, t, r, b, adv), (gx, gy, w, h) in zip(glyphs, places):
        f.write("    {%d, %d, %d, %d, %d, %d, %.3ff}, // '%s'\n" % (gx, gy, w, h, l, t, adv, chr(c) if chr(c) not in "\\'" else "\\" + chr(c)))
    f.write("};\n\n// 4-bit alpha, one hex digit per pixel, row-major top-down.\n")
    f.write("inline const char* Pixels[] = {\n")
    for ln in lines:
        f.write('    "%s",\n' % ln)
    f.write("};\nconstexpr int PixelLines = %d;\nconstexpr int CharsPerLine = 120;\n\n} // namespace Lapis::FontData\n" % len(lines))
print("atlas", W, "x", H, "lines", len(lines))
